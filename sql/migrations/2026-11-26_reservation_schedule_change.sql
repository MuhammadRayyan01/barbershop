CREATE TABLE IF NOT EXISTS public.reservation_schedule_change (
    schedule_change_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id integer NOT NULL REFERENCES public.reservation(reservation_id),
    old_slot_id integer NOT NULL REFERENCES public.time_slot(slot_id),
    new_slot_id integer NOT NULL REFERENCES public.time_slot(slot_id),
    admin_id integer NOT NULL REFERENCES public.admin(admin_id),
    customer_agreed boolean NOT NULL CHECK (customer_agreed = TRUE),
    reason varchar(500) NOT NULL DEFAULT 'Kendala operasional',
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT reservation_schedule_change_different_slots CHECK (old_slot_id <> new_slot_id)
);

CREATE INDEX IF NOT EXISTS idx_reservation_schedule_change_reservation
    ON public.reservation_schedule_change (reservation_id, created_at DESC);
