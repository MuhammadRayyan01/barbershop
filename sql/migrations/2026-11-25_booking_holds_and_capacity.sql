ALTER TABLE public.time_slot
    ADD COLUMN IF NOT EXISTS booking_capacity smallint NOT NULL DEFAULT 3;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'time_slot_booking_capacity_range'
          AND conrelid = 'public.time_slot'::regclass
    ) THEN
        ALTER TABLE public.time_slot
            ADD CONSTRAINT time_slot_booking_capacity_range
            CHECK (booking_capacity BETWEEN 0 AND 3);
    END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS public.booking_hold (
    hold_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hold_token varchar(64) NOT NULL UNIQUE,
    user_id integer NOT NULL REFERENCES public.users(user_id),
    slot_id integer NOT NULL REFERENCES public.time_slot(slot_id),
    service_id integer NOT NULL REFERENCES public.service(service_id),
    service_price numeric(10,2) NOT NULL CHECK (service_price >= 0),
    additional_service_id integer REFERENCES public.additional_service(additional_service_id),
    additional_service_price numeric(10,2),
    total_amount numeric(10,2) NOT NULL CHECK (total_amount > 0),
    hold_status varchar(20) NOT NULL DEFAULT 'active'
        CHECK (hold_status IN ('active', 'converted', 'expired', 'released', 'failed')),
    expires_at timestamptz NOT NULL,
    midtrans_order_id varchar(255) UNIQUE,
    snap_token text,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reservation_id integer UNIQUE REFERENCES public.reservation(reservation_id),
    CONSTRAINT check_booking_hold_additional_price CHECK (
        (additional_service_id IS NULL AND additional_service_price IS NULL)
        OR (additional_service_id IS NOT NULL AND additional_service_price IS NOT NULL AND additional_service_price >= 0)
    ),
    CONSTRAINT check_booking_hold_total CHECK (
        total_amount = service_price + COALESCE(additional_service_price, 0)
    )
);

CREATE INDEX IF NOT EXISTS idx_booking_hold_expiration
    ON public.booking_hold (expires_at) WHERE hold_status = 'active';
CREATE INDEX IF NOT EXISTS idx_booking_hold_slot_status_expiry
    ON public.booking_hold (slot_id, hold_status, expires_at);
CREATE INDEX IF NOT EXISTS idx_booking_hold_user_status
    ON public.booking_hold (user_id, hold_status);
